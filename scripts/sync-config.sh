#!/usr/bin/env bash
# Single source of truth for the Nginx site config is docker/nginx/default.conf.
# This script copies it into the places that need their own copy:
#   - kubernetes/configmap.yaml            (plain manifests)
#   - helm/ecommerce/files/default.conf    (Helm chart, rendered into a ConfigMap)
# Run it after every change to docker/nginx/default.conf. "scripts/test.sh" fails if they differ.
set -euo pipefail
source "$(dirname "$0")/lib/common.sh"

SRC="$REPO_ROOT/docker/nginx/default.conf"
[ -f "$SRC" ] || die "Missing $SRC"

mkdir -p "$REPO_ROOT/helm/ecommerce/files"
cp "$SRC" "$REPO_ROOT/helm/ecommerce/files/default.conf"

{
  cat <<'YAML'
# GENERATED by scripts/sync-config.sh from docker/nginx/default.conf - do not edit by hand.
apiVersion: v1
kind: ConfigMap
metadata:
  name: nexvion-nginx
  namespace: nexvion
  labels:
    app.kubernetes.io/name: ecommerce
    app.kubernetes.io/part-of: nexvion
data:
  default.conf: |
YAML
  sed 's/^/    /' "$SRC"
} > "$REPO_ROOT/kubernetes/configmap.yaml"

log_ok "Synced nginx config into kubernetes/configmap.yaml and helm/ecommerce/files/default.conf"
